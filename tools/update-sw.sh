#!/usr/bin/env bash
# Regenerates sw.js: the list of files to keep offline and a version taken from their contents,
# so phones fetch the new copy after every update. Run before each publish:  bash tools/update-sw.sh
cd "$(dirname "$0")/.." || exit 1
files=$(git ls-files --cached --others --exclude-standard | grep -v -E '^(sw\.js|app/|tools/|README\.md|\.gitignore|\.nojekyll|fonts/meyer1570-source/)' | sort)
version=$(cat $files | sha1sum | cut -c1-10)
{
  echo "// Posta hut offline helper (generated by tools/update-sw.sh — don't edit by hand)."
  echo "// First visit: saves every game file. Afterwards the game runs from that copy, online or not;"
  echo "// when online it checks for a newer version, which takes over on the next launch."
  echo "const VERSION = \"$version\";"
  echo "const FILES = ["
  echo "  \"./\","
  for f in $files; do echo "  \"$f\","; done
  echo "];"
  cat <<'JS'
const CACHE = "posta-hut-" + VERSION;
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("posta-hut-") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  // the saved copy first (works offline); if a file isn't saved, fetch it and keep it
  e.respondWith(caches.open(CACHE).then((c) => c.match(req, { ignoreSearch: true }).then((hit) =>
    hit || fetch(req).then((res) => { if (res.ok) c.put(req, res.clone()); return res; })
      .catch(() => (req.mode === "navigate" ? c.match("index.html") : Response.error())))));
});
JS
} > sw.js
echo "sw.js: $(echo "$files" | wc -l) files, version $version"
